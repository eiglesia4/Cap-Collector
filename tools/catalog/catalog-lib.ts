// Pure part of the test catalog (method.md § Tests): turns `vitest list --json` into TEST.md and enforces test IDs.
import { relative } from 'node:path';

/** Components allowed in `[T-<comp>-nnn]` (method.md § Jira project). */
export const COMPONENTS = ['app', 'api', 'shared', 'infra', 'vision', 'print', 'exchange'] as const;

/** One item of `vitest list --json`. */
export interface ListedTest {
  name: string;
  file: string;
  projectName?: string;
}

export interface CatalogEntry {
  id: string;
  title: string;
  file: string;
  project: string;
}

export interface CatalogResult {
  entries: CatalogEntry[];
  errors: string[];
}

const ID_RE = /\[T-([a-z]+)-(\d{3})\]\s*(.*)$/;

/**
 * Extracts one entry per test. Errors: a test without ID, an unknown component, an ID used twice.
 * Entries come back sorted by component, then number, so TEST.md is stable.
 */
export function buildCatalog(tests: readonly ListedTest[], root: string): CatalogResult {
  const errors: string[] = [];
  const seen = new Map<string, CatalogEntry>();

  for (const t of tests) {
    const file = relative(root, t.file);
    const match = ID_RE.exec(t.name);
    if (!match) {
      errors.push(`${file}: test without [T-<comp>-nnn] ID: "${t.name}"`);
      continue;
    }
    const [, comp = '', num = '', title = ''] = match;
    if (!(COMPONENTS as readonly string[]).includes(comp)) {
      errors.push(`${file}: unknown component "${comp}" in "${t.name}" (allowed: ${COMPONENTS.join(', ')})`);
      continue;
    }
    const id = `T-${comp}-${num}`;
    const previous = seen.get(id);
    if (previous) {
      errors.push(`${id} used twice: ${previous.file} and ${file}`);
      continue;
    }
    seen.set(id, { id, title: title.trim(), file, project: t.projectName ?? '' });
  }

  const entries = [...seen.values()].sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));
  return { entries, errors };
}

const escapeCell = (s: string) => s.replace(/\|/g, '\\|');

/** Renders TEST.md. Deterministic: no dates, no absolute paths. */
export function renderTestMd(entries: readonly CatalogEntry[]): string {
  const lines = [
    '# TEST.md — test catalog',
    '',
    '<!-- Generated by `npm run catalog` from the test titles. Do not edit by hand. -->',
    '',
    `${entries.length} tests. IDs are \`[T-<comp>-nnn]\`, never reused (doc/spec/method.md § Tests).`,
    '',
    '| ID | Test | Workspace | File |',
    '|---|---|---|---|',
    ...entries.map((e) => `| ${e.id} | ${escapeCell(e.title)} | ${e.project} | \`${e.file}\` |`),
    '',
  ];
  return lines.join('\n');
}

/** IDs listed in a TEST.md, in order of appearance (used to check each appears exactly once). */
export function idsInTestMd(markdown: string): string[] {
  return [...markdown.matchAll(/^\| (T-[a-z]+-\d{3}) \|/gm)].map((m) => m[1] ?? '');
}
